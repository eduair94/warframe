import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const SOURCE_URL = 'https://raw.githubusercontent.com/WFCD/warframe-items/master/data/json/Mods.json'
const OUTPUT_URL = new URL('../app/app/data/modSyndicates.ts', import.meta.url)
const SYNDICATES = [
  'Steel Meridian',
  'Arbiters of Hexis',
  'Cephalon Suda',
  'The Perrin Sequence',
  'Red Veil',
  'New Loka',
]

function normalizeModName(name) {
  return String(name || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/gi, '')
    .toLowerCase()
}

const response = await fetch(SOURCE_URL)
if (!response.ok) {
  throw new Error(`Could not download ${SOURCE_URL}: HTTP ${response.status}`)
}

const items = await response.json()
const byMod = new Map()

for (const item of items) {
  const modName = String(item?.name || '').trim()
  if (!modName) continue

  const locations = Array.isArray(item?.drops)
    ? item.drops.map((drop) => String(drop?.location || ''))
    : []
  const offeredBy = SYNDICATES.filter((syndicate) =>
    locations.some((location) => location === syndicate || location.startsWith(`${syndicate},`)),
  )
  if (!offeredBy.length) continue

  const key = normalizeModName(modName)
  const known = byMod.get(key) || new Set()
  for (const syndicate of offeredBy) known.add(syndicate)
  byMod.set(key, known)
}

const rows = [...byMod.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, syndicates]) => `  ${JSON.stringify(key)}: ${JSON.stringify([...syndicates])},`)
  .join('\n')

const generated = `// Generated by scripts/gen-mod-syndicates.mjs from:
// ${SOURCE_URL}
// Do not edit this mapping by hand; rerun the generator when the upstream item data changes.

export const SYNDICATE_ORDER = ${JSON.stringify(SYNDICATES, null, 2)} as const

export type SyndicateName = (typeof SYNDICATE_ORDER)[number]

const MOD_SYNDICATES: Readonly<Record<string, readonly SyndicateName[]>> = {
${rows}
}

const NO_SYNDICATES: readonly SyndicateName[] = []

export function normalizeModName(name: string): string {
  return String(name || '')
    .normalize('NFKD')
    .replace(/[\\u0300-\\u036f]/g, '')
    .replace(/[^a-z0-9]+/gi, '')
    .toLowerCase()
}

export function syndicatesForMod(itemName: string): readonly SyndicateName[] {
  return MOD_SYNDICATES[normalizeModName(itemName)] || NO_SYNDICATES
}
`

await writeFile(OUTPUT_URL, generated, 'utf8')
console.log(`Wrote ${byMod.size} syndicate mod mappings to ${fileURLToPath(OUTPUT_URL)}`)
